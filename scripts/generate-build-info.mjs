import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))

function git(args, fallback = '') {
  try {
    return execSync(`git ${args}`, {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore']
    }).trim()
  } catch {
    return fallback
  }
}

const env = process.env
const commitSha = env.GITHUB_SHA || git('rev-parse HEAD', 'unknown')
const shortCommitSha = commitSha === 'unknown' ? 'unknown' : commitSha.slice(0, 7)
const gitRef = env.GITHUB_REF_NAME || git('branch --show-current', 'local')
const buildDate = env.BUILD_DATE || new Date().toISOString()

function releaseChannel() {
  if (env.RELEASE_CHANNEL) return env.RELEASE_CHANNEL
  if (/^v?\d+\.\d+\.\d+/.test(gitRef)) return gitRef.includes('-') ? 'beta' : 'stable'
  if (String(pkg.version).includes('-')) return 'beta'
  return 'dev'
}

const info = {
  name: pkg.name,
  productName: 'Časomíra',
  version: pkg.version,
  commitSha,
  shortCommitSha,
  buildDate,
  releaseChannel: releaseChannel(),
  gitRef,
  packagedBy: env.GITHUB_ACTIONS === 'true' ? 'github-actions' : 'local'
}

const target = resolve(root, 'src/shared/buildInfo.generated.ts')
const body = `// Auto-generated by scripts/generate-build-info.mjs. Do not edit by hand.
// Commit this file so local typecheck works; release builds regenerate it.

export const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const
`

writeFileSync(target, body)
console.log(`build info: ${info.version} ${info.shortCommitSha} ${info.releaseChannel}`)
